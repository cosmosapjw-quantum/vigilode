#!/usr/bin/env python3
"""Union of Cargo.lock v4 package entries for the standalone diffsol adapter.

    python3 -s merge_locks.py LOCK_A LOCK_B > merged.lock

Seeds the adapter's lock from the checkout's lock (the rodas5p crates'
dependency versions) and the archived ncp_intensive diffsol lock (diffsol
=0.17.1 and its graph). Two versions of one crate in one semver-compatible
class (e.g. thiserror 2.0.19 and 2.0.21) cannot coexist in one graph, so only
the highest is kept, and dependency references are rewritten to it. Cargo
prunes unused entries; setup_ncp.sh falls back to the archived lock alone and
then to an offline resolution if this seed does not resolve.
"""
import re
import sys


def parse(text):
    pkgs = []
    for raw in text.split("\n[[package]]\n")[1:]:
        lines = raw.strip("\n").splitlines()
        p = {"deps": [], "extra": []}
        i = 0
        while i < len(lines):
            line = lines[i]
            if line.startswith("dependencies = ["):
                i += 1
                while not lines[i].startswith("]"):
                    p["deps"].append(lines[i].strip().rstrip(",").strip('"'))
                    i += 1
            elif " = " in line:
                k, v = line.split(" = ", 1)
                if k in ("name", "version", "source", "checksum"):
                    p[k] = v.strip('"')
                else:
                    p["extra"].append(line)
            i += 1
        pkgs.append(p)
    return pkgs


def vtuple(v):
    return tuple(int(x) for x in re.findall(r"\d+", v.split("-")[0])[:3])


def compat(v):
    t = vtuple(v)
    return t[:1] if t[0] > 0 else (t[:2] if t[1] > 0 else t[:3])


best = {}
for path in sys.argv[1:]:
    for p in parse(open(path).read()):
        key = (p["name"], p.get("source"), compat(p["version"]))
        if key not in best or vtuple(p["version"]) > vtuple(best[key]["version"]):
            best[key] = p
kept = list(best.values())
versions = {}
for p in kept:
    versions.setdefault(p["name"], []).append(p)


def rewrite(dep):
    parts = dep.split(" ", 2)
    name = parts[0]
    cands = versions.get(name, [])
    if len(cands) == 1:
        return name
    if len(parts) >= 2:
        want = compat(parts[1])
        for c in cands:
            if compat(c["version"]) == want:
                return f"{name} {c['version']}"
    return dep


out = []
for p in sorted(kept, key=lambda p: (p["name"], vtuple(p["version"]))):
    s = [f'name = "{p["name"]}"', f'version = "{p["version"]}"']
    if p.get("source"):
        s.append(f'source = "{p["source"]}"')
    if p.get("checksum"):
        s.append(f'checksum = "{p["checksum"]}"')
    s += p["extra"]
    if p["deps"]:
        s.append("dependencies = [")
        s += [f' "{rewrite(d)}",' for d in sorted(set(p["deps"]))]
        s.append("]")
    out.append("[[package]]\n" + "\n".join(s) + "\n")
sys.stdout.write("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n"
                 "version = 4\n\n" + "\n".join(out))
