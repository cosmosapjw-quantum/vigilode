"""Generate finite O(n) rational cyclic solve circuits; no symbolic determinant expansion."""
import json,time,pathlib
HERE=pathlib.Path(__file__).resolve().parent

def source(n):
    z=[f'template<class T> std::vector<T> circuit_{n}(const std::vector<T>&q,const std::vector<T>&f){{',f' std::vector<T> b({n}),v({n});']
    z += [f' b[{i}]=q[{(i+1)%n}]*T(0.5);' for i in range(n)]
    z += [f' T r=f[{n-1}],p=-b[{n-1}];']
    for i in range(n-2,-1,-1):z += [f' r=f[{i}]-b[{i}]*r; p=-b[{i}]*p;']
    z += [' v[0]=r/(T(1)-p);',f' v[{n-1}]=f[{n-1}]-b[{n-1}]*v[0];']
    for i in range(n-2,0,-1):z += [f' v[{i}]=f[{i}]-b[{i}]*v[{i+1}];']
    z+=[' return v;','}']
    return '\n'.join(z)+'\n'

def generate():
    records=[];parts=['// Generated by generate.py; exact rational cyclic inverse circuit.\n']
    for n in (4,8,16):
        t=time.perf_counter_ns();s=source(n);ns=time.perf_counter_ns()-t
        records.append(dict(n=n,source_bytes=len(s.encode()),source_lines=len(s.splitlines()),arithmetic_ops=7*n-3,negations=n,add_sub=2*n-1,mul=4*n-3,div=1,codegen_ns=ns,largest_literal_numerator=1,largest_literal_denominator=2,recurrence_registers=2,expression_swell='linear DAG; expanded determinant intentionally avoided'))
        parts.append(s)
    parts.append('template<class T> std::vector<T> compiled_solve(const std::vector<T>&q,const std::vector<T>&f){switch(q.size()){case 4:return circuit_4(q,f);case 8:return circuit_8(q,f);case 16:return circuit_16(q,f);default:throw std::runtime_error("unsupported n");}}\n')
    (HERE/'circuits.hpp').write_text(''.join(parts));return records
if __name__=='__main__':print(json.dumps(generate(),indent=2))
