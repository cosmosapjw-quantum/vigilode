def reaction_step(u0: float,x0: float,a: float):
    """Implicit local balance, algebraically eliminated using u+x=Q.

    a=h*k is dimensionless; this is backward Euler, NOT fifth-order time stepping.
    Stable physical root when u0>=0, 0<=x0<=1 and a>=0, finite.
    """
    if not all(math.isfinite(x) for x in (u0,x0,a)) or u0<0 or not 0<=x0<=1 or a<0:
        raise ValueError('outside physical parameter cell')
    q=u0+x0
    b=1+a*(q+1)
    # Equivalent nonnegative discriminant decomposition, avoids cancellation.
    disc=1+2*a*(q+1-2*x0)+a*a*(q-1)**2
    x=2*(x0+a*q)/(b+math.sqrt(disc))
    return q-x,x

def algebraic_reaction():
    rows=[]
    for u0,x0 in [(0.6,0.2),(0.8,0.2),(1.2,0.2),(0.,1.)]:
        for a in [0.,1e-8,0.1,1.,1e3,1e6]:
            u,x=reaction_step(u0,x0,a)
            residual=x-x0-a*u*(1-x)
            # Backward-error normalized by all terms (not forward error).
            norm=abs(residual)/(1+abs(x)+abs(x0)+a*abs(u*(1-x)))
            assert abs((u+x)-(u0+x0))<=4e-16
            assert u>=-1e-14 and x>=x0-1e-14 and x<=1+1e-14
            assert norm<1e-9, (u0,x0,a,residual,norm)
            rows.append(dict(u0=u0,x0=x0,hk=a,u_new=u,x_new=x,normalized_balance_residual=norm))
    return {'kind':'algebraic_local_resolvent_test','rows':rows,'derivative_calls':0,
            'order':'backward Euler only; proposed as local nonlinear preconditioner',
            'forward_error_certified':False}

def lowrank_packet():
    """Exact semidiscrete collective reduction with a stiff periodic stencil.
    y'=nu*L_h y-lam*y-alpha*mean(y)^2*1.
    All independent initial modes are retained in the Fourier reconstruction.
    The source sink is a declared toy collective feedback, NOT atomic physics.
    """
    nu,lam,alpha=0.01,0.7,0.4
    ts=np.linspace(0,0.3,51)
    results=[]
    for n in [32,128,1600]:
        i=np.arange(n);y0=0.6+0.08*np.cos(2*np.pi*i/n)+0.03*np.sin(6*np.pi*i/n)
        m0=float(np.mean(y0));a0=np.fft.fft(y0-m0)
        rates=-4*nu*n*n*np.sin(np.pi*np.arange(n)/n)**2-lam
        m=m0*np.exp(-lam*ts)/(1+(alpha*m0/lam)*(-np.expm1(-lam*ts)))
        reconstructed=np.array([m[k]+np.fft.ifft(np.exp(rates*t)*a0).real for k,t in enumerate(ts)])
        mean_error=float(np.max(np.abs(np.mean(reconstructed,axis=1)-m)))
        assert mean_error<1e-14
        row={'n':n,'physical_stencil_spectral_radius':float(np.max(np.abs(rates))),
             'nonlinear_dimension':1,'nonlinear_state_jacobian_or_jvp_calls':0,
             'retained_initial_values':n,'mean_identity_error':mean_error,
             'min_state':float(reconstructed.min()),'timing_claim':False}
        if n==32:
            def rhs(t,y):return nu*n*n*(np.roll(y,1)-2*y+np.roll(y,-1))-lam*y-alpha*np.mean(y)**2
            reference=solve_ivp(rhs,[ts[0],ts[-1]],y0,method='DOP853',t_eval=ts,rtol=2e-12,atol=2e-14)
            assert reference.success
            error=float(np.max(np.abs(reference.y.T-reconstructed)))
            assert error<3e-10
            row.update(reference_solver='DOP853 tight tolerance; reference only',max_absolute_difference=error)
        results.append(row)
    # Counterexample to closure: same scalar mean, different mean derivative
    # for spatially varying absorption sigma_i.
    sigma=np.array([1.,3.]);y=np.array([1.,0.]);z=np.array([0.,1.])
    assert y.mean()==z.mean()
    slopes=[float(-np.mean(sigma*v)) for v in [y,z]]
    assert slopes[0]!=slopes[1]
    return {'models':results,'closure_negative_control':{'same_mean':0.5,'mean_derivatives':slopes,
        'reason':'diagonal material-dependent absorption cannot generally be replaced by mean-only forcing'},
        'scope':'periodic linear stencil + exactly rank-one feedback; not generic radiation transport'}

def schur_control():
    """Physical block solve only. Exact band solve + exact Schur gives degree2.

    Neither this operator nor preconditioner is generated by differentiating an
    unknown nonlinear RHS. This is not evidence for 2/3/5 iterations on all PDEs.
    """
    rows=[]
    for n in [32,128]:
        a=300.;r=2
        ab=np.zeros((3,n));ab[1]=1+2*a;ab[0,1:]=-a;ab[2,:-1]=-a
        grid=np.arange(1,n+1)/(n+1)
        B=np.c_[0.2*np.sin(np.pi*grid),0.15*np.cos(2*np.pi*grid)]
        C=0.1*B.T/n;D=np.diag([2.,3.])
        invB=solve_banded((1,1),ab,B)
        schur=D-C@invB
        def action(x):
            u=x[:n];v=x[n:]
            Au=(1+2*a)*u.copy();Au[1:]-=a*u[:-1];Au[:-1]-=a*u[1:]
            return np.r_[Au+B@v,C@u+D@v]
        def exact_pre(v):
            u=solve_banded((1,1),ab,v[:n]);m=np.linalg.solve(schur,v[n:]-C@u)
            return np.r_[u,m]
        operator=LinearOperator((n+r,n+r),matvec=action)
        rhs=np.sin(np.arange(n+r)*0.723)+np.cos(np.arange(n+r)*0.315)
        for label,pre in [('diagonal',lambda v:np.r_[v[:n]/(1+2*a),v[n:]/np.diag(D)]),('exact_band_schur',exact_pre)]:
            count=[0]
            def cb(_):count[0]+=1
            sol,info=gmres(operator,rhs,M=LinearOperator((n+r,n+r),matvec=pre),restart=n+r,maxiter=3,
                           rtol=1e-10,atol=1e-13,callback=cb,callback_type='pr_norm')
            err=float(np.linalg.norm(action(sol)-rhs)/np.linalg.norm(rhs))
            assert info==0 and err<2e-10
            rows.append({'n_radiation':n,'border_dimension':r,'preconditioner':label,'iterations':count[0],
                         'relative_residual':err})
        assert rows[-1]['iterations']<=3
        assert rows[-2]['iterations']>5
    return {'results':rows,'claim':'exact block identity, not approximate preconditioner iteration guarantee',
            'build_and_apply_cost_not_benchmarked':True}

def polyadd(a,b):
    c=[F(0)]*max(len(a),len(b))
    for i,x in enumerate(a):c[i]+=x
    for i,x in enumerate(b):c[i]+=x
    return c

def polymul(a,b):
    c=[F(0)]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):c[i+j]+=x*y
    return c

def bernstein(coeff,h):
    degree=len(coeff)-1
    return [sum((coeff[j]*h**j*F(math.comb(k,j),math.comb(degree,j)) for j in range(k+1)),F(0)) for k in range(degree+1)]

def rational_defect_certificate():
    """An EXACT rational certificate for the polynomial candidate itself.

    y'=-2y-y^2, y(0)=1/2 on [0,h]. Both true and candidate curves nonnegative.
    (y-z)(f(y)-f(z))=-(2+y+z)(y-z)^2 gives mu<=-2 with no derivative call.
    Bernstein convex hull bounds full continuous defect, NOT sampled residuals.
    Rational Taylor lower bound for exp(-2h) gives rigorous endpoint radius.
    The certificate is for exact rational curve evaluation, not returned binary64.
    """
    coeff=[F(1,2)]
    for k in range(5):
        coeff.append((-2*coeff[k]-sum((coeff[j]*coeff[k-j] for j in range(k+1)),F(0)))/F(k+1))
    derivative=[(i+1)*coeff[i+1] for i in range(len(coeff)-1)]
    defect=polyadd(polyadd(derivative,[2*x for x in coeff]),polymul(coeff,coeff))
    mp.mp.dps=70
    def high(x):return mp.mpf(x.numerator)/x.denominator
    rows=[]
    for h in [F(1,4),F(1,8),F(1,16)]:
        bc=bernstein(coeff,h);bd=bernstein(defect,h)
        delta=max(abs(x) for x in bd)
        # x<=1/2; alternating exponential truncation at odd degree is lower.
        z=2*h
        exp_lower=sum(((-z)**k/F(math.factorial(k)) for k in range(12)),F(0))
        endpoint=delta*(1-exp_lower)/2
        simple=delta*h
        assert min(bc)-simple>0
        assert max(bc)+simple<1
        # Invariance y>=0 is exact for this scalar field; tube/q stay in[0,1].
        actual=[];bounds=[]
        for t in np.linspace(0,float(h),501):
            tt=mp.mpf(str(t))
            exact=mp.mpf('.5')*mp.exp(-2*tt)/(1+mp.mpf('.25')*(1-mp.exp(-2*tt)))
            q=sum(high(a)*tt**k for k,a in enumerate(coeff))
            actual.append(abs(q-exact));bounds.append(high(delta)*(1-mp.exp(-2*tt))/2)
        assert all(e<=b+mp.mpf('1e-65') for e,b in zip(actual,bounds))
        exact_h=mp.mpf('.5')*mp.exp(-2*high(h))/(1+mp.mpf('.25')*(1-mp.exp(-2*high(h))))
        q_h=sum(a*h**k for k,a in enumerate(coeff));end_error=abs(high(q_h)-exact_h)
        assert end_error<=high(endpoint)
        rows.append({'h':str(h),'candidate_degree':5,'residual_degree':len(defect)-1,
                     'continuous_defect_upper_rational':str(delta),'endpoint_radius_rational':str(endpoint),
                     'endpoint_radius_float':float(endpoint),'endpoint_actual_error_mp':float(end_error),
                     'worst_sampled_error_mp':float(max(actual)),'q_positive_bernstein':float(min(bc)),
                     'exact_rational_certificate':True,'binary64_evaluation_rounding_included':False})
    return {'equation':'y\u2032=-2y-y^2','initial':'1/2','polynomial_coefficients':[str(x) for x in coeff],
            'results':rows,'derivative_of_nonlinear_rhs_used':False,'time_derivative_of_candidate_used':True,
            'sampled_mp_checks_are_not_the_proof':True,'proof':'exact Bernstein convex hull + two-point dissipativity + comparison'}

def frozen_factor_control():
    rows=[]
    for steps in [10,20,40,80,160,320]:
        T=.4;dt=T/steps;y=1.
        for _ in range(steps):y*=math.exp(y*dt)
        exact=1/(1-T)
        rows.append({'steps':steps,'dt':dt,'error':abs(y-exact)})
    slopes=[math.log(rows[i]['error']/rows[i+1]['error'],2) for i in range(len(rows)-1)]
    assert .90<slopes[-1]<1.1
    return {'equation':'y\u2032=y^2','frozen_step':'ynew=yn*exp(h*yn): frozen subproblem solved exactly',
            'local_difference':'-h^2/2+O(h^3) at y0=1','results':rows,'observed_global_orders':slopes}

def conservative_remap_control():
    rows=[]
    for n in [32,64,128,256]:
        edge=np.linspace(0,1,n+1)
        mass=(edge[1:]-edge[:-1])+(.2/(2*np.pi))*(np.cos(2*np.pi*edge[:-1])-np.cos(2*np.pi*edge[1:]))
        coarse=mass.reshape(-1,2).sum(axis=1)
        remap=np.repeat(coarse/2,2)
        err=float(np.sum(np.abs(remap-mass)))
        conservation=float(abs(remap.sum()-mass.sum()))
        assert conservation<1e-14
        rows.append({'cells':n,'integrated_l1_error':err,'conservation_residual':conservation})
    slopes=[math.log(rows[i]['integrated_l1_error']/rows[i+1]['integrated_l1_error'],2) for i in range(len(rows)-1)]
    assert all(abs(x-1)<.03 for x in slopes)
    return {'procedure':'exact original cell integrals -> merge pairs -> split constant average',
            'results':rows,'spatial_orders':slopes,'claim':'conservation does not imply high-order remapping'}

