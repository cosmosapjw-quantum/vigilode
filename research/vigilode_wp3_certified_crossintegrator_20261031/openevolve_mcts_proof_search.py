"""Offline alternating OpenEvolve MAP-Elites and UCT proof-lemma search.

Actual OpenEvolve 0.4.0 ProgramDatabase persists candidate cards. Candidates
are generated by the research assistant and scored by separately evaluated
exact-rational Bernstein certifier; NO external LLM/API is invoked.
The PUCT-inspired UCT search allocates proof exploration, not neural inference.
"""
