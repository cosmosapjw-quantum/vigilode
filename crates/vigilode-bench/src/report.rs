//! Markdown report generated from the results JSON only.
//!
//! Every number printed comes from a JSON number formatted by [`fmt_number`]
//! or from a JSON string copied verbatim; `tests/report.rs` checks this.

use serde_json::Value;

/// The one number formatter of the report: integers as integers, everything
/// else in `{:.3e}`.
pub fn fmt_number(v: &serde_json::Number) -> String {
    if let Some(i) = v.as_i64() {
        return i.to_string();
    }
    if let Some(u) = v.as_u64() {
        return u.to_string();
    }
    let f = v.as_f64().unwrap_or(f64::NAN);
    if f.fract() == 0.0 && f.abs() < 1e15 {
        format!("{}", f as i64)
    } else {
        format!("{f:.3e}")
    }
}

/// Format any JSON value for a table cell.
pub fn cell(v: &Value) -> String {
    match v {
        Value::Null => "—".into(),
        Value::Bool(b) => if *b { "yes" } else { "no" }.into(),
        Value::Number(n) => fmt_number(n),
        Value::String(s) => s.replace('|', "\\|"),
        Value::Array(a) => a.iter().map(cell).collect::<Vec<_>>().join(", "),
        Value::Object(_) => v.to_string().replace('|', "\\|"),
    }
}

fn at<'a>(v: &'a Value, path: &[&str]) -> &'a Value {
    let mut cur = v;
    for k in path {
        cur = cur.get(*k).unwrap_or(&Value::Null);
    }
    cur
}

fn c(v: &Value, path: &[&str]) -> String {
    cell(at(v, path))
}

fn status(v: &Value) -> String {
    match v.get("kind").and_then(Value::as_str) {
        Some("success") => "success".into(),
        Some(k) => match v.get("message") {
            Some(m) => format!("{k}: {}", cell(m)),
            None => k.into(),
        },
        None => cell(v),
    }
}

fn table(out: &mut String, header: &[&str], rows: Vec<Vec<String>>) {
    out.push_str(&format!("| {} |\n", header.join(" | ")));
    out.push_str(&format!("|{}\n", " --- |".repeat(header.len())));
    for r in rows {
        out.push_str(&format!("| {} |\n", r.join(" | ")));
    }
    out.push('\n');
}

/// Generate the report.
pub fn render(doc: &Value) -> Result<String, String> {
    if doc.get("schema").and_then(Value::as_str) != Some(crate::harness::RESULTS_SCHEMA) {
        return Err("not a vigilode-bench results document".into());
    }
    let mut o = String::new();
    o.push_str("# E1-bench work–precision report\n\n");
    o.push_str(
        "Generated by `vigilode-bench report` from the results JSON; do not edit by hand.\n\n",
    );
    o.push_str(&format!(
        "Timing authority: **{}** — {}\n\n",
        c(doc, &["timing_authority"]),
        c(doc, &["timing_note"])
    ));

    o.push_str("## Provenance\n\n");
    let prov = at(doc, &["provenance"]);
    let mut prow = Vec::new();
    if let Value::Object(m) = prov {
        for (k, v) in m {
            prow.push(vec![format!("`{k}`"), cell(v)]);
        }
    }
    prow.push(vec!["corpus".into(), c(doc, &["corpus", "id"])]);
    prow.push(vec![
        "grid points".into(),
        c(doc, &["corpus", "grid_points"]),
    ]);
    prow.push(vec!["rtols".into(), c(doc, &["corpus", "rtols"])]);
    prow.push(vec!["warm-ups".into(), c(doc, &["corpus", "warmups"])]);
    prow.push(vec![
        "repetitions".into(),
        c(doc, &["corpus", "repetitions"]),
    ]);
    prow.push(vec!["error_rtol".into(), c(doc, &["corpus", "error_rtol"])]);
    prow.push(vec!["run seconds".into(), c(doc, &["run_seconds"])]);
    prow.push(vec![
        "allocations measured".into(),
        c(doc, &["allocation_measurement", "measured"]),
    ]);
    prow.push(vec![
        "allocation scope".into(),
        c(doc, &["allocation_measurement", "scope"]),
    ]);
    table(&mut o, &["item", "value"], prow);

    o.push_str("## Problems and references\n\n");
    let problems = at(doc, &["corpus", "problems"])
        .as_array()
        .cloned()
        .unwrap_or_default();
    table(
        &mut o,
        &[
            "problem",
            "kind",
            "n",
            "t_end",
            "atol scale",
            "reference atol",
            "banded arms",
        ],
        problems
            .iter()
            .map(|p| {
                vec![
                    c(p, &["id"]),
                    c(p, &["kind"]),
                    c(p, &["n"]),
                    c(p, &["t_end"]),
                    cell(at(p, &["atol_scale"]).get(0).unwrap_or(&Value::Null)),
                    c(p, &["reference_atol"]),
                    c(p, &["banded"]),
                ]
            })
            .collect(),
    );
    let refs = at(doc, &["references"])
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut rrows = Vec::new();
    for r in &refs {
        let mut add = |x: &Value, role: &str| {
            rrows.push(vec![
                c(r, &["problem"]),
                role.into(),
                c(x, &["arm"]),
                c(x, &["rtol_used"]),
                c(x, &["disagreement"]),
            ])
        };
        add(at(r, &["crosscheck"]), "decisive");
        for x in at(r, &["informational"])
            .as_array()
            .cloned()
            .unwrap_or_default()
        {
            add(&x, "informational");
        }
    }
    table(
        &mut o,
        &[
            "problem",
            "reference arm",
            "rtol",
            "atol",
            "status",
            "disputed",
        ],
        refs.iter()
            .map(|r| {
                vec![
                    c(r, &["problem"]),
                    c(r, &["arm"]),
                    c(r, &["rtol"]),
                    c(r, &["atol"]),
                    status(at(r, &["status"])),
                    c(r, &["disputed"]),
                ]
            })
            .collect(),
    );
    o.push_str(&format!(
        "Cross-checks: disagreement is measured like `error_common`; a decisive disagreement above {} marks the problem `reference-disputed`.\n\n",
        c(doc, &["corpus", "reference", "dispute_threshold"])
    ));
    table(
        &mut o,
        &["problem", "role", "arm", "rtol used", "disagreement"],
        rrows,
    );

    o.push_str("## Matched-error comparison\n\n");
    o.push_str(&format!("Common levels of `error_common`: {}. At each level both arms' median wall time and RHS count are interpolated in log–log on their own successful points. `time_ratio = comparator / VigilODE` (above 1: VigilODE faster). Ratios exist only where both arms bracket the level; every other entry is `DIAGNOSTIC_ONLY`. Band-structured comparators are compared with `vigilode-banded`, the others with `vigilode`. Reference-implementation-only arms are excluded.\n\n", c(doc, &["corpus", "error_levels"])));
    o.push_str("The comparison is not between unconstrained solvers: the VigilODE arms land a step on every one of the grid times (the facade offers no dense output), so their step size is capped by the grid spacing and the extra steps are inside every VigilODE time and RHS count, while every comparator steps freely and interpolates. The table below gives, for every VigilODE row, the accepted steps and how many of them were clipped to a grid time.\n\n");
    let rows_all = at(doc, &["rows"]).as_array().cloned().unwrap_or_default();
    table(
        &mut o,
        &[
            "problem",
            "arm",
            "rtol",
            "accepted steps",
            "output-clipped steps",
            "internal steps",
        ],
        rows_all
            .iter()
            .filter(|r| c(r, &["comparator_fidelity"]) == "solver-under-test")
            .map(|r| {
                vec![
                    c(r, &["problem"]),
                    c(r, &["arm"]),
                    c(r, &["rtol"]),
                    c(r, &["work", "accepted_steps"]),
                    c(r, &["native", "output_clipped_steps"]),
                    c(r, &["native", "internal_steps"]),
                ]
            })
            .collect(),
    );
    let matched = at(doc, &["matched"])
        .as_array()
        .cloned()
        .unwrap_or_default();
    table(
        &mut o,
        &[
            "problem",
            "comparator",
            "baseline",
            "error level",
            "status",
            "time ratio",
            "rhs ratio",
            "comparator ms",
            "baseline ms",
            "reason",
        ],
        matched
            .iter()
            .map(|m| {
                vec![
                    c(m, &["problem"]),
                    c(m, &["arm"]),
                    c(m, &["baseline"]),
                    c(m, &["error_level"]),
                    c(m, &["status"]),
                    c(m, &["time_ratio"]),
                    c(m, &["rhs_ratio"]),
                    c(m, &["comparator_wall_ms"]),
                    c(m, &["baseline_wall_ms"]),
                    c(m, &["reason"]),
                ]
            })
            .collect(),
    );

    o.push_str("## Rows\n\n");
    o.push_str("`error_common`: max over the grid of the WRMS error against the reference with weights `error_rtol (atol_scale + |y_ref|)`; `error_own`: the same with the run's own weights `rtol (atol_scale + |y_ref|)`, i.e. its own atol vector and rtol. Work counts are solver-reported (`—`: not reported; `clipped`: VigilODE steps shortened to land on a grid time); `rhs`, `jac`, `jvp` are the shared model's callback counts. Allocations: every heap allocation call of the run (`heap`) and its Rust subset (`rust`). Failed runs are kept with their work.\n\n");
    let rows = at(doc, &["rows"]).as_array().cloned().unwrap_or_default();
    for p in &problems {
        let id = c(p, &["id"]);
        o.push_str(&format!("### {id}\n\n"));
        table(
            &mut o,
            &[
                "arm",
                "fidelity",
                "rtol",
                "status",
                "grid",
                "error_common",
                "error_own",
                "ms",
                "acc",
                "clipped",
                "rej",
                "LU",
                "rhs",
                "jac",
                "jvp",
                "heap",
                "rust",
                "det",
            ],
            rows.iter()
                .filter(|r| c(r, &["problem"]) == id)
                .map(|r| {
                    vec![
                        c(r, &["arm"]),
                        c(r, &["comparator_fidelity"]),
                        c(r, &["rtol"]),
                        status(at(r, &["status"])),
                        c(r, &["grid_points_completed"]),
                        c(r, &["error_common"]),
                        c(r, &["error_wrms_own"]),
                        c(r, &["wall_ms_median"]),
                        c(r, &["work", "accepted_steps"]),
                        c(r, &["native", "output_clipped_steps"]),
                        c(r, &["work", "rejected_steps"]),
                        c(r, &["work", "factorizations"]),
                        c(r, &["callbacks", "rhs"]),
                        c(r, &["callbacks", "jac"]),
                        c(r, &["callbacks", "jvp"]),
                        c(r, &["allocations", "heap_calls"]),
                        c(r, &["allocations", "rust_calls"]),
                        c(r, &["deterministic"]),
                    ]
                })
                .collect(),
        );
    }

    o.push_str("## Arms\n\n");
    let mut seen: Vec<String> = Vec::new();
    let mut arows = Vec::new();
    for r in &rows {
        let a = c(r, &["arm"]);
        if seen.contains(&a) {
            continue;
        }
        seen.push(a.clone());
        arows.push(vec![
            a,
            c(r, &["comparator_fidelity"]),
            c(r, &["output_interface"]),
            c(r, &["deviations"]),
        ]);
    }
    table(
        &mut o,
        &[
            "arm",
            "fidelity",
            "output interface",
            "deviations from vendor defaults",
        ],
        arows,
    );
    Ok(o)
}

/// Every numeric token of a text: split on separators, keep tokens that parse
/// as a finite `f64` and contain a digit.
pub fn numeric_tokens(text: &str) -> Vec<String> {
    text.split(|ch: char| {
        ch.is_whitespace()
            || matches!(
                ch,
                '|' | '('
                    | ')'
                    | ','
                    | ':'
                    | ';'
                    | '='
                    | '/'
                    | '`'
                    | '*'
                    | '['
                    | ']'
                    | '{'
                    | '}'
                    | '"'
                    | '<'
                    | '>'
            )
    })
    .map(|t| t.trim_end_matches('.'))
    .filter(|t| {
        t.chars().any(|ch| ch.is_ascii_digit()) && t.parse::<f64>().is_ok_and(f64::is_finite)
    })
    .map(str::to_string)
    .collect()
}
